//! Python emitter: `TypedDict` classes, `Literal` enums and `Union` aliases, standard library only (Python 3.9+).
//!
//! References to other types are quoted so the file does not depend on definition order. Objects nested inside a
//! schema become their own classes named after their parent and field.

use std::collections::HashSet;

use crate::schema::{Def, Lit, Object, Ty, Variant};

const WIDTH: usize = 120;
const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
    "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
    "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
];

struct State {
    used: HashSet<String>,
    /// Classes hoisted out of the definition being rendered, in the order they must appear.
    helpers: Vec<String>,
}

pub fn render(defs: &[Def]) -> String {
    let mut st = State { used: defs.iter().map(|d| d.name.clone()).collect(), helpers: Vec::new() };
    let mut out = String::from(
        "# Generated by `cargo xtask contracts` from docs/api/openapi.json. Do not edit.\n\
         # Types only: nothing here exists at runtime except the names.\n\
         \"\"\"Typed shapes of the ProxyMind REST API (TypedDict, Literal and Union aliases).\"\"\"\n\n\
         import typing as _t\n\n\
         from typing import TypedDict\n",
    );
    for d in defs {
        let main = st.definition(d);
        for h in st.helpers.drain(..) {
            out.push_str("\n\n");
            out.push_str(&h);
        }
        out.push_str("\n\n");
        out.push_str(&main);
    }
    out
}

fn is_ident(s: &str) -> bool {
    let mut c = s.chars();
    c.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && c.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !KEYWORDS.contains(&s)
}

fn pascal(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        })
        .collect()
}

fn comment(text: &str, ind: usize) -> String {
    let pad = " ".repeat(ind);
    text.lines()
        .map(|l| if l.trim().is_empty() { format!("{pad}#\n") } else { format!("{pad}# {}\n", l.trim_end()) })
        .collect()
}

fn docstring(text: &str) -> String {
    let t = text.replace('\\', "\\\\").replace("\"\"\"", "\\\"\\\"\\\"");
    let lines: Vec<&str> = t.lines().map(str::trim_end).collect();
    if lines.len() == 1 && lines[0].len() + 10 <= WIDTH {
        return format!("    \"\"\"{}\"\"\"\n", lines[0]);
    }
    let mut s = String::from("    \"\"\"");
    for (i, l) in lines.iter().enumerate() {
        if i > 0 {
            s.push('\n');
            if !l.is_empty() {
                s.push_str("    ");
            }
        }
        s.push_str(l);
    }
    s.push_str("\n    \"\"\"\n");
    s
}

fn py_lit(l: &Lit) -> String {
    match l {
        Lit::Str(s) => serde_json::to_string(s).unwrap_or_default(),
        Lit::Num(n) => n.clone(),
        Lit::Bool(true) => "True".into(),
        Lit::Bool(false) => "False".into(),
    }
}

impl State {
    fn unique(&mut self, base: &str) -> String {
        let mut name = base.to_string();
        let mut n = 2;
        while self.used.contains(&name) {
            name = format!("{base}{n}");
            n += 1;
        }
        self.used.insert(name.clone());
        name
    }

    fn definition(&mut self, d: &Def) -> String {
        match &d.ty {
            Ty::Object(o) => self.class(&d.name, d.doc.as_deref(), o),
            t => {
                let mut s = String::new();
                if let Some(doc) = &d.doc {
                    s.push_str(&comment(doc, 0));
                }
                let prefix = format!("{} = ", d.name);
                let rhs = match t {
                    Ty::Union(vs) => {
                        let members = self.members(vs, &d.name);
                        let one = format!("_t.Union[{}]", members.join(", "));
                        if members.len() > 1 && prefix.len() + one.len() > WIDTH {
                            let inner: String = members.iter().map(|m| format!("    {m},\n")).collect();
                            format!("_t.Union[\n{inner}]")
                        } else {
                            self.union_expr(members)
                        }
                    }
                    Ty::Ref(n) => format!("_t.Union[\"{n}\"]"),
                    other => self.ty(other, &d.name),
                };
                s.push_str(&prefix);
                s.push_str(&rhs);
                s
            }
        }
    }

    fn field_ty(&mut self, o: &Object, class: &str) -> Vec<String> {
        o.fields.iter().map(|f| self.ty(&f.ty, &format!("{class}{}", pascal(&f.name)))).collect()
    }

    /// A `TypedDict` for `o`, with required and optional keys split the way Python 3.9 needs.
    fn class(&mut self, name: &str, doc: Option<&str>, o: &Object) -> String {
        let tys = self.field_ty(o, name);
        let fields: Vec<(&crate::schema::Field, &String)> = o.fields.iter().zip(tys.iter()).collect();
        let (req, opt): (Vec<_>, Vec<_>) = fields.into_iter().partition(|(f, _)| f.required);
        let plain = o.fields.iter().all(|f| is_ident(&f.name));
        let body = |group: &[(&crate::schema::Field, &String)]| -> String {
            group
                .iter()
                .map(|(f, t)| {
                    let mut s = f.doc.as_deref().map(|d| comment(d, 4)).unwrap_or_default();
                    s.push_str(&format!("    {}: {t}\n", f.name));
                    s
                })
                .collect()
        };
        let dict = |group: &[(&crate::schema::Field, &String)]| -> String {
            group
                .iter()
                .map(|(f, t)| format!("    {}: {t},\n", serde_json::to_string(&f.name).unwrap_or_default()))
                .collect()
        };
        let mut s = String::new();
        if plain {
            if !req.is_empty() && !opt.is_empty() {
                s.push_str(&format!("class _{name}Required(TypedDict):\n{}\n\n", body(&req)));
                s.push_str(&format!("class {name}(_{name}Required, total=False):\n"));
                s.push_str(&doc.map(docstring).unwrap_or_default());
                s.push_str(&body(&opt));
            } else {
                let total = if req.is_empty() && !opt.is_empty() { "TypedDict, total=False" } else { "TypedDict" };
                s.push_str(&format!("class {name}({total}):\n"));
                s.push_str(&doc.map(docstring).unwrap_or_default());
                let b = body(&if req.is_empty() { opt } else { req });
                s.push_str(if b.is_empty() && doc.is_none() { "    pass\n" } else { &b });
            }
        } else {
            // Keys that are not Python identifiers: the functional syntax.
            if let Some(d) = doc {
                s.push_str(&comment(d, 0));
            }
            if !req.is_empty() && !opt.is_empty() {
                s.push_str(&format!("_{name}Required = TypedDict(\"_{name}Required\", {{\n{}}})\n\n", dict(&req)));
                s.push_str(&format!(
                    "_{name}Optional = TypedDict(\"_{name}Optional\", {{\n{}}}, total=False)\n\n",
                    dict(&opt)
                ));
                s.push_str(&format!("class {name}(_{name}Required, _{name}Optional):\n    pass\n"));
            } else {
                let total = if req.is_empty() { ", total=False" } else { "" };
                let g = if req.is_empty() { opt } else { req };
                s.push_str(&format!("{name} = TypedDict(\"{name}\", {{\n{}}}{total})\n", dict(&g)));
            }
        }
        s.trim_end().to_string() + "\n"
    }

    /// Union members as Python expressions; string/number/bool literals are grouped into one `Literal`.
    fn members(&mut self, vs: &[Variant], hint: &str) -> Vec<String> {
        let mut lits: Vec<String> = Vec::new();
        let mut others: Vec<String> = Vec::new();
        let mut none = false;
        for (i, v) in vs.iter().enumerate() {
            match &v.ty {
                Ty::Lit(l) => lits.push(py_lit(l)),
                Ty::Null => none = true,
                Ty::Object(o) => {
                    let tag = o
                        .fields
                        .iter()
                        .find_map(|f| match (&f.ty, f.required) {
                            (Ty::Lit(Lit::Str(s)), true) => Some(pascal(s)),
                            _ => None,
                        })
                        .unwrap_or_else(|| format!("Variant{}", i + 1));
                    let name = self.unique(&format!("{hint}{tag}"));
                    let class = self.class(&name, v.doc.as_deref(), o);
                    self.helpers.push(class);
                    others.push(format!("\"{name}\""));
                }
                t => others.push(self.ty(t, hint)),
            }
        }
        let mut out = Vec::new();
        if !lits.is_empty() {
            out.push(format!("_t.Literal[{}]", lits.join(", ")));
        }
        out.extend(others);
        if none {
            out.push("None".into());
        }
        out
    }

    fn union_expr(&mut self, members: Vec<String>) -> String {
        match members.as_slice() {
            [one] => one.clone(),
            [a, n] if n == "None" => format!("_t.Optional[{a}]"),
            _ => format!("_t.Union[{}]", members.join(", ")),
        }
    }

    fn ty(&mut self, t: &Ty, hint: &str) -> String {
        match t {
            Ty::Unknown | Ty::Never | Ty::Inter(_) => "_t.Any".into(),
            Ty::Null => "None".into(),
            Ty::Str => "str".into(),
            Ty::Int => "int".into(),
            Ty::Num => "float".into(),
            Ty::Bool => "bool".into(),
            Ty::Ref(n) => format!("\"{n}\""),
            Ty::Lit(l) => format!("_t.Literal[{}]", py_lit(l)),
            Ty::Array(i) => format!("_t.List[{}]", self.ty(i, hint)),
            Ty::Tuple(items) => {
                let parts: Vec<String> = items.iter().map(|i| self.ty(i, hint)).collect();
                format!("_t.Tuple[{}]", parts.join(", "))
            }
            Ty::Map(v) => format!("_t.Dict[str, {}]", self.ty(v, hint)),
            Ty::Object(o) => {
                let name = self.unique(hint);
                let class = self.class(&name, None, o);
                self.helpers.push(class);
                format!("\"{name}\"")
            }
            Ty::Union(vs) => {
                let members = self.members(vs, hint);
                self.union_expr(members)
            }
        }
    }
}
