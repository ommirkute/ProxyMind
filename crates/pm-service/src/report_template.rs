//! Report templates: built-in executive, technical and compliance reports
//! in HTML and Markdown, and templates people write themselves (MiniJinja,
//! project setting `report_templates`). Any HTML report can be printed to
//! PDF in a headless Chromium (scripts off, no network).
//!
//! Templates get `r` (the structured `Report`), `css` (the built-in style)
//! and `cwe_url(n)`. HTML templates escape every value automatically:
//! findings hold text from the target. Rendering has a fuel limit, so a
//! template can't loop forever.

use minijinja::{AutoEscape, Environment, context};
use pm_policy::{Actor, ActorKind};
use serde::{Deserialize, Serialize};
use serde_json::json;

use crate::report::{CSS, Report, ReportOptions};
use crate::{Result, Service, ServiceError};

/// Project setting that holds the saved templates as JSON.
pub const TEMPLATES_SETTING: &str = "report_templates";

/// Largest template body.
const MAX_BODY: usize = 200 * 1024;

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct ReportTemplate {
    pub name: String,
    pub description: String,
    /// html or md
    pub format: String,
    /// MiniJinja source. Empty for the built-in technical HTML report.
    pub body: String,
    /// Set by the service.
    pub builtin: bool,
}

/// A rendered report.
#[derive(Debug, Clone)]
pub struct Rendered {
    pub content_type: &'static str,
    pub extension: &'static str,
    pub body: Vec<u8>,
}

