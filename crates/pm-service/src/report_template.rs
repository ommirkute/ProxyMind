impl Service {
    /// Built-in templates first, then saved ones.
    pub fn report_templates(&self) -> Result<Vec<ReportTemplate>> {
        let mut all = builtin_templates();
        all.extend(self.store.read(load_saved)?);
        Ok(all)
    }

    /// Saves (adds or replaces) a template after checking it renders. Humans only.
    pub fn report_template_save(&self, actor: &Actor, mut t: ReportTemplate) -> Result<Vec<ReportTemplate>> {
        if actor.kind != ActorKind::Human {
            return Err(ServiceError::Invalid("only humans can change report templates".into()));
        }
        t.name = t.name.trim().to_string();
        t.builtin = false;
        let n = &t.name;
        if n.is_empty() || n.len() > 40 || !n.chars().all(|c| c.is_ascii_alphanumeric() || "-_ ".contains(c)) {
            return Err(ServiceError::Invalid("template names are 1-40 letters, digits, spaces, - or _".into()));
        }
        if builtin_templates().iter().any(|b| b.name.eq_ignore_ascii_case(n)) {
            return Err(ServiceError::Invalid(format!("{n} is a built-in template; save yours under another name")));
        }
        if !matches!(t.format.as_str(), "html" | "md") {
            return Err(ServiceError::Invalid("format is html or md".into()));
        }
        if t.body.trim().is_empty() || t.body.len() > MAX_BODY {
            return Err(ServiceError::Invalid(format!("a template body is 1 to {MAX_BODY} bytes")));
        }
        render_body(&t.body, &t.format, &sample_report()).map_err(ServiceError::Invalid)?;
        self.store.write(|store| -> Result<()> {
            let mut saved = load_saved(store)?;
            saved.retain(|s| !(s.name.eq_ignore_ascii_case(&t.name) && s.format == t.format));
            saved.push(t.clone());
            if saved.len() > 50 {
                return Err(ServiceError::Invalid("at most 50 saved templates".into()));
            }
            let text = serde_json::to_string(&saved).map_err(|e| ServiceError::Invalid(e.to_string()))?;
            store.set_setting(TEMPLATES_SETTING, &text)?;
            Ok(())
        })?;
        self.audit(&actor.id(), "report_template_save", json!({ "name": t.name, "format": t.format }), "allow")?;
        self.report_templates()
    }

    pub fn report_template_delete(&self, actor: &Actor, name: &str) -> Result<bool> {
        if actor.kind != ActorKind::Human {
            return Err(ServiceError::Invalid("only humans can change report templates".into()));
        }
        let removed = self.store.write(|store| -> Result<bool> {
            let mut saved = load_saved(store)?;
            let before = saved.len();
            saved.retain(|s| !s.name.eq_ignore_ascii_case(name));
            let text = serde_json::to_string(&saved).map_err(|e| ServiceError::Invalid(e.to_string()))?;
            store.set_setting(TEMPLATES_SETTING, &text)?;
            Ok(saved.len() < before)
        })?;
        self.audit(
            &actor.id(),
            "report_template_delete",
            json!({ "name": name }),
            if removed { "allow" } else { "noop" },
        )?;
        Ok(removed)
    }

    /// Renders a report. `format`: html, md, pdf, json or sarif; `template`
    /// (default technical) applies to html, md and pdf.
    pub async fn report_render(&self, template: Option<&str>, format: &str, opts: &ReportOptions) -> Result<Rendered> {
        let r = self.report_with(opts)?;
        let name = template.filter(|t| !t.trim().is_empty()).unwrap_or("technical");
        let html_or_md = |fmt: &str| -> Result<String> {
            let t = self
                .report_templates()?
                .into_iter()
                .find(|t| t.name.eq_ignore_ascii_case(name) && t.format == fmt)
                .ok_or_else(|| ServiceError::NotFound(format!("report template {name} ({fmt})")))?;
            if t.builtin && t.body.is_empty() {
                return Ok(crate::report::html(&r));
            }
            render_body(&t.body, fmt, &r).map_err(ServiceError::Invalid)
        };
        Ok(match format {
            "json" => Rendered {
                content_type: "application/json",
                extension: "json",
                body: serde_json::to_vec_pretty(&r).unwrap_or_default(),
            },
            "sarif" => Rendered {
                content_type: "application/sarif+json",
                extension: "sarif",
                body: serde_json::to_vec_pretty(&crate::report::sarif(&r)).unwrap_or_default(),
            },
            "md" | "markdown" => Rendered {
                content_type: "text/markdown; charset=utf-8",
                extension: "md",
                body: html_or_md("md")?.into_bytes(),
            },
            "html" => Rendered {
                content_type: "text/html; charset=utf-8",
                extension: "html",
                body: html_or_md("html")?.into_bytes(),
            },
            "pdf" => {
                let html = html_or_md("html")?;
                let chromium = pm_browser::find_chromium()
                    .ok_or_else(|| ServiceError::Invalid("PDF needs Chromium or Chrome installed".into()))?;
                let b64 = pm_browser::print_pdf(&chromium, html.as_bytes())
                    .await
                    .map_err(|e| ServiceError::Invalid(format!("printing the PDF failed: {e}")))?;
                let body = pm_tools::codec::base64_decode(&b64, false)
                    .map_err(|e| ServiceError::Invalid(format!("the browser's PDF was unreadable: {e}")))?;
                Rendered { content_type: "application/pdf", extension: "pdf", body }
            }
            other => {
                return Err(ServiceError::Invalid(format!(
                    "unknown report format {other}: use html, md, pdf, json or sarif"
                )));
            }
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn builtins_render_and_escape_target_text() {
        let mut r = sample_report();
        r.findings[0].title = "<script>alert(1)</script>".into();
        r.summarise();
        for t in builtin_templates().into_iter().filter(|t| !t.body.is_empty()) {
            let out = render_body(&t.body, &t.format, &r).unwrap_or_else(|e| panic!("{} {}: {e}", t.name, t.format));
            if t.format == "html" {
                assert!(!out.contains("<script>alert(1)"), "{} escapes", t.name);
                assert!(out.contains("default-src 'none'"));
            }
            assert!(out.contains("Sample"), "{} {}", t.name, t.format);
        }
        let exec = render_body(EXECUTIVE_MD, "md", &r).unwrap();
        assert!(exec.contains("**Overall risk:** high"), "{exec}");
        assert!(exec.contains("SQL injection") && exec.contains("parameterised queries"), "{exec}");
        let comp = render_body(COMPLIANCE_HTML, "html", &r).unwrap();
        assert!(comp.contains("A03:2021 Injection") && comp.contains("CWE-89"), "{comp}");
    }

    #[test]
    fn bad_and_endless_templates_are_refused() {
        let r = sample_report();
        assert!(render_body("{% for x in r.findings %}", "md", &r).is_err());
        let endless = "{% for i in range(100000) %}{% for j in range(100000) %}x{% endfor %}{% endfor %}";
        assert!(render_body(endless, "md", &r).is_err(), "fuel stops it");
    }
}
